#!/usr/bin/env python
"""paper2_dynport_table.py — 论文2 §7（贡献③）的时间放置对照表（机写，零手抄）。

读已过工件：
  * 离线（PASS 形态）：results/dynport_offline/evidence_L3/manifest_offline_L1_L3.json
      —— 21 格（全 7 序列 × 3 seed；L1_v4/L2 复用件已并入同一 manifest），
         出口口径 = samepose（prereg §12 v4）。取 J1/J2/J3/J4_ratio 的格间区间 +
         通过格数（J3∧J1∧J2）。
  * 在线（FAIL 形态）：results/dynport/evidence/manifest_L1_v2.json
      —— crowd2/balloon2（v2 批，HEAD f0fcdb6f8）。J1/J2 = causal_snapshot（含位姿混杂，
         见 D1-032 §6bis），J3 = final-map，J4_overhead = mapping 相位开销占比。

输出：results/paper2_fulltable/evidence/latex/tab_dynport.tex
（\input 前须过关卡②；产物随 evidence/latex 入库，并由
 tests/paper2_fulltable/test_paper2_codec_tables_committed.py 守护逐字节一致。）

表 = **描述性**放置对照（跨放置含 4 处共变：位姿源/静态保护/KF 日程/掩码通路）⇒
不作单变量因果主张；在线行须在 caption 标注口径与批号（D1-027 禁跨放置混引）。
"""
from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OFF_MAN = REPO / "results/dynport_offline/evidence_L3/manifest_offline_L1_L3.json"
ON_MAN = REPO / "results/dynport/evidence/manifest_L1_v2.json"
OUT = REPO / "results/paper2_fulltable/evidence/latex/tab_dynport.tex"

SEQ_ONLINE = ["crowd2", "balloon2"]  # v2 批两序列（顺序固定，禁随 dict 顺序漂移）


def _gain_range(vals, nd=2):
    """正增益区间：$+a$--$+b$（数学模式 ⇒ 真正的加号与 en dash）。"""
    return f"${min(vals):+.{nd}f}$--${max(vals):+.{nd}f}$"


def _signed_range(vals, nd=3):
    """带符号区间：数学模式（真减号/加号），端点间用 "to" 以免与负号混淆。"""
    return f"${min(vals):+.{nd}f}$ to ${max(vals):+.{nd}f}$"


def _ratio_range(vals, nd=2):
    return f"{min(vals):.{nd}f}--{max(vals):.{nd}f}"


def _pair(vals, nd=2, signed=False):
    if signed:
        return "$" + "/".join(f"{v:+.{nd}f}" for v in vals) + "$"
    return "/".join(f"{v:.{nd}f}" for v in vals)


def offline_block(man):
    s = man["summary"]
    ok = [v for v in s.values() if abs(v["J3"]) <= 0.25 and v["J1"] >= 2.5 and v["J2"] <= 0.70]
    return {
        "n_cells": len(s),
        "n_pass": len(ok),
        "J1": _gain_range([v["J1"] for v in s.values()]),
        "J2": _ratio_range([v["J2"] for v in s.values()]),
        "J3": _signed_range([v["J3"] for v in s.values()]),
        "J4": f"{_ratio_range([v['J4_ratio'] for v in s.values()])}$\\times$",        "head": man["head"],
    }


def online_block(man):
    s = man["summary"]
    costs = [s[q]["J4_overhead"] * 100 for q in SEQ_ONLINE]
    return {
        "J1": _pair([s[q]["J1"] for q in SEQ_ONLINE], signed=True),
        "J2": _pair([s[q]["J2"] for q in SEQ_ONLINE]),
        "J3": _pair([s[q]["J3"] for q in SEQ_ONLINE], signed=True),
        "J4": "/".join(f"+{c:.1f}" for c in costs),
        "seqs": SEQ_ONLINE,
        "head": man["head"],
    }


def build_tex(off, on) -> str:
    L = []
    L.append("% generated by scripts/dynport_offline/paper2_dynport_table.py -- do not edit by hand")
    L.append(f"% provenance: results/dynport_offline/evidence_L3/manifest_offline_L1_L3.json "
             f"(HEAD {off['head']})")
    L.append(f"% provenance: results/dynport/evidence/manifest_L1_v2.json (HEAD {on['head']})")
    L.append("\\begin{table*}")
    L.append("\\begin{center}")
    L.append("\\footnotesize")
    L.append("\\begin{tabular}{@{}lccccc@{}}")
    L.append("\\toprule")
    L.append("Placement & J1 dynamic (dB) & J2 depth ratio & J3 static (dB) & Cost & Outcome \\\\")
    L.append("\\midrule")
    L.append(f"Online & {on['J1']} & {on['J2']} & {on['J3']} & ${on['J4']}\\%$ & fail \\\\")
    L.append("Erase (reference) & $0$ & $1$ & $0$ & --- & --- \\\\")
    L.append(f"Offline & {off['J1']} & {off['J2']} & {off['J3']} & {off['J4']} & "
             f"pass {off['n_pass']}/{off['n_cells']} \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    L.append("\\end{center}")
    cap = (
        "The same dynamic Gaussian management, run online and offline, against the erase "
        "baseline. J1/J2 are dynamic-region metrics, J3 static-region; online cost is per-frame "
        "mapping overhead, offline cost is the repair's share of the base run's online "
        "wall-clock. "
        f"Offline is the full seven-sequence, three-seed grid ({off['n_cells']} cells, all "
        "passing); online covers two sequences (crowd2, balloon2, seed 0). The "
        "comparison is descriptive, not "
        "single-variable: moving offline changes four things at once (pose source, static-layer "
        "freezing, keyframe schedule, mask pathway). The online dynamic readings use a "
        "snapshot instrument whose poses differ from the evaluated frame and carry a pose "
        "confound, so they are not comparable to the offline numbers."
    )
    L.append(f"\\caption{{{cap}}}")
    L.append("\\label{tab:dynport}")
    L.append("\\end{table*}")
    L.append("")
    return "\n".join(L)


def main():
    off = offline_block(json.loads(OFF_MAN.read_text()))
    on = online_block(json.loads(ON_MAN.read_text()))
    tex = build_tex(off, on)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(tex)
    print(f"wrote {OUT}")
    print(tex)


if __name__ == "__main__":
    main()
