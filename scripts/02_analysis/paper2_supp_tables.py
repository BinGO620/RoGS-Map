# ─────────────────────────── S8 修复逐格（序列 × seed） ───────────────────────────
def s8_repair():
    files = sorted(E3.glob("dynport_offline_L1_*_samepose.json"))
    rows = []
    for f in files:
        j = json.loads(f.read_text())
        seq = j.get("seq", "?")
        base = seq.split("_seed")[0]
        sd = seq.split("_seed")[1] if "_seed" in seq else "0"
        rows.append((base, sd, j))
    rows.sort(key=lambda x: (x[0], x[1]))
    print(f"[s8] {len(files)} 个判据文件；样例 = {files[0].name if files else 'NONE'}")
    L = ["% generated by scripts/02_analysis/paper2_supp_tables.py -- do not edit by hand",
         "% provenance: results/dynport_offline/evidence_L3/dynport_offline_L1_*_L3_samepose.json",
         "% 锁定阈值：J1 >= 2.5 dB；J2 <= 0.70；J3 within ±0.25 dB（prereg_dynport_offline_L1.md §3）"]
    L.append(r"\begin{table}[t]")
    L.append(r"\centering\footnotesize\setlength{\tabcolsep}{5pt}")
    L.append(r"\begin{tabular}{@{}lcccc@{}}")
    L.append(r"\toprule")
    L.append(r"\emph{Cell} & J1 (dB) & J2 & J3 (dB) & pass \\")
    L.append(r"\midrule")
    n_pass = 0
    for base, sd, j in rows:
        j1 = j["J1_samepose_bad_psnr_delta"]["median"]
        j2 = j["J2_samepose_bad_dl1_ratio"]["median"]
        j3 = j["J3_samepose_static_delta"]["median"]
        ok = (j1 >= 2.5) and (j2 <= 0.70) and (abs(j3) <= 0.25)
        n_pass += int(ok)
        lab = f"{SEQ_LAB.get(base, base)} (seed {sd})"
        L.append(f"{lab} & {j1:.2f} & {j2:.3f} & ${j3:+.2f}$ & "
                 + (r"\checkmark" if ok else r"$\times$") + r" \\")
    L.append(r"\bottomrule")
    L.append(r"\end{tabular}")
    L.append(r"\caption{Offline repair, per sequence and seed: J1 = dynamic-region PSNR gain "
             r"over the erased baseline; J2 = residual depth error as a fraction of the "
             r"erased value; J3 = static-region change. Samepose medians; locked thresholds "
             r"J1 $\ge$ 2.5\,dB, J2 $\le$ 0.70, J3 within $\pm$0.25\,dB. Passed cells: "
             f"{n_pass}/{len(rows)}.}}")
    L.append(r"\label{tabS:repair}")
    L.append(r"\end{table}")
    _w("supp_repair.tex", "\n".join(L) + "\n")


