# ─────────────────────────── S5 codec 逐序列三工作点 ───────────────────────────
def s5_codec_seq():
    d = json.loads((RD / "l2_summary.json").read_text())
    WPS = ["near_lossless", "mid", "aggressive"]
    per = {s: {w: {"r": [], "p": []} for w in WPS} for s in SEQ7}
    src = {s: [] for s in SEQ7}
    src_key = None
    for k, v in d.items():
        if not isinstance(v, dict):
            continue
        # 键形如 <seq>_<arm>（arm ∈ baseline/final）——按后缀剥离，
        # 避免 rsplit 误切含下划线的序列名（person_tracking2 曾因此并入 person_tracking）
        if k.endswith("_baseline"):
            seq = k[: -len("_baseline")]
        elif k.endswith("_final"):
            seq = k[: -len("_final")]
        else:
            continue
        if seq not in per:
            continue
        for w in WPS:
            wv = v.get(w)
            if wv:
                per[seq][w]["r"].append(wv.get("ratio_full"))
                per[seq][w]["p"].append(wv.get("psnr"))
        # 源 PSNR 字段探测（结构未定时给清晰报错）
        for cand in ("source", "src", "base", "raw"):
            sv = v.get(cand)
            if isinstance(sv, dict) and "psnr" in sv:
                src_key = cand
                src[seq].append(sv["psnr"])
                break
        else:
            if "psnr_src" in v:
                src_key = "psnr_src"
                src[seq].append(v["psnr_src"])
    print(f"[s5] 源 PSNR 字段 = {src_key}；样例键 = {list(d.keys())[:3]}")
    L = ["% generated by scripts/02_analysis/paper2_supp_tables.py -- do not edit by hand",
         "% provenance: results/gs_compress/evidence/rd/l2_summary.json（42 图：7 序列 × 2 臂 × 3 seed）",
         "% 口径：ratio = 源 20 字段 f32 字节 / 存储字节；PSNR = 全图渲染（同正文仪器）"]
    L.append(r"\begin{table}[t]")
    L.append(r"\centering\footnotesize\setlength{\tabcolsep}{3pt}")
    L.append(r"\begin{tabular}{@{}l" + "cc" * len(WPS) + r"@{}}")
    L.append(r"\toprule")
    L.append(r"& \multicolumn{2}{c}{\emph{near-lossless}} & \multicolumn{2}{c}{\emph{mid}} "
             r"& \multicolumn{2}{c}{\emph{aggressive}} \\")
    L.append(r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}\cmidrule(lr){6-7}")
    have_delta = src_key is not None
    pcol = r"$\Delta$PSNR" if have_delta else "PSNR"
    L.append(r"\emph{Sequence} & ratio & " + pcol + r" & ratio & " + pcol
             + r" & ratio & " + pcol + r" \\")
    L.append(r"\midrule")
    for s in SEQ7:
        cells = []
        sbase = float(np.mean(src[s])) if have_delta and src[s] else None
        for w in WPS:
            r = float(np.mean([x for x in per[s][w]["r"] if x is not None])) if per[s][w]["r"] else None
            p = float(np.mean([x for x in per[s][w]["p"] if x is not None])) if per[s][w]["p"] else None
            rt = f"{r:.2f}$\\times$" if r else "--"
            if have_delta and p is not None and sbase is not None:
                cells += [rt, f"${p - sbase:+.2f}$"]
            else:
                cells += [rt, (f"{p:.2f}" if p is not None else "--")]
        L.append(SEQ_LAB.get(s, s) + " & " + " & ".join(cells) + r" \\")
    L.append(r"\bottomrule")
    L.append(r"\end{tabular}")
    dcol = r"$\Delta$PSNR is the change from the uncompressed source (negative = loss); " \
        if have_delta else r"PSNR is the absolute full-image value; "
    L.append(r"\caption{Codec working points per sequence (mean over the sequence's maps: "
             r"2 arms $\times$ 3 seeds). Bit widths are the fixed working points "
             r"(16/8/8/8/8, 10/6/6/6/6, 8/4/4/4/4); only the per-map quantisation ranges are "
             r"fitted per map. " + dcol +
             r"held-out-panel values are in the main text (\S5).}")
    L.append(r"\label{tabS:codec-seq}")
    L.append(r"\end{table}")
    _w("supp_codec_seq.tex", "\n".join(L) + "\n")


# ─────────────────────────── S6 learned 基线明细 ───────────────────────────
def s6_learned():
    L = ["% generated by scripts/02_analysis/paper2_supp_tables.py -- do not edit by hand",
         "% provenance: evidence/rd/learned_sog_L{2,3}.json + learned_nied_L{2,3}.json",
         "% 口径：同分母（n_src*20*4）、同仪器（render_compare 固定帧集）；SOG 非排序官方通路"]
    L.append(r"\begin{table}[t]")
    L.append(r"\centering\footnotesize\setlength{\tabcolsep}{5pt}")
    L.append(r"\begin{tabular}{@{}llcccc@{}}")
    L.append(r"\toprule")
    L.append(r"\emph{Configuration} & \emph{Split} & n & ratio & B/prim & PSNR \\")
    L.append(r"\midrule")
    for split, fname in (("L2 (frozen maps)", "learned_sog_L2.json"), ("L3 (held-out)", "learned_sog_L3.json")):
        d = json.loads((RD / fname).read_text())
        for cfg in d["configs"]:
            rr = [r for r in d["rows"] if r["config"] == cfg]
            ratio = float(np.mean([r["ratio_full"] for r in rr]))
            bpp = float(np.mean([r["rate_bytes_per_prim"] for r in rr]))
            pd_ = [r.get("psnr_delta") for r in rr if r.get("psnr_delta") is not None]
            pstr = f"${float(np.mean(pd_)):+.2f}$" if pd_ else "--"
            lab = "SOG (JXL, unquantised)" if cfg == "jxl_101" else "SOG (JXL, quantised)"
            L.append(f"{lab} & {split} & {len(rr)} & {ratio:.2f}$\\times$ & {bpp:.1f} & {pstr} \\\\")
    L.append(r"\midrule")
    for split, fname in (("L2 (frozen maps)", "learned_nied_L2.json"), ("L3 (held-out)", "learned_nied_L3.json")):
        p = RD / fname
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        i5 = d.get("iters5000") or d
        rr = i5.get("rows") or []
        if not rr:
            continue
        ratio = float(np.mean([r["ratio_full"] for r in rr]))
        bpp = float(np.mean([r["rate_bytes_per_prim"] for r in rr]))
        ps = [r["render"]["mean_psnr"] for r in rr if r.get("render")]
        L.append(f"Niedermayr c3dgs (QAT 5k) & {split} & {len(rr)} & {ratio:.2f}$\\times$ & "
                 f"{bpp:.1f} & {float(np.mean(ps)):.2f} \\\\")
    L.append(r"\bottomrule")
    L.append(r"\end{tabular}")
    L.append(r"\caption{Learned-compressor detail. SOG's PSNR column is its change from the "
             r"source ($\Delta$PSNR); Niedermayr's is the absolute rendered PSNR (its refit "
             r"seeds nothing, so per-map values are not reproducible beyond $\approx$0.1\,dB "
             r"and no $\Delta$ is claimed). Bookkeeping fields that SOG does not carry are "
             r"compressed losslessly (lzma-9) and counted in the numerator; the denominator is "
             r"unchanged. Working-point comparison against the parameter-free codec is in "
             r"Table~4 of the main paper.}")
    L.append(r"\label{tabS:learned}")
    L.append(r"\end{table}")
    _w("supp_learned.tex", "\n".join(L) + "\n")


